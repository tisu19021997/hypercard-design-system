// Generates crisp 1-bit PNG tiles and CSS custom properties from the pattern JSON files, plus the browse cursor.
// No dependencies: a minimal PNG encoder on top of node:zlib. Run: node scripts/build-patterns.mjs
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = f => JSON.parse(fs.readFileSync(path.join(root, f), 'utf8'));

const crcTable = Array.from({ length: 256 }, (_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
const crc32 = buf => { let c = 0xffffffff; for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
const chunk = (type, data) => { const len = Buffer.alloc(4); len.writeUInt32BE(data.length); const td = Buffer.concat([Buffer.from(type), data]); const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td)); return Buffer.concat([len, td, crc]); };
// pixels: array of rows, each row an array of [r,g,b,a]
export function png(pixels) {
  const h = pixels.length, w = pixels[0].length;
  const raw = Buffer.alloc((w * 4 + 1) * h);
  pixels.forEach((row, y) => { raw[y * (w * 4 + 1)] = 0; row.forEach((p, x) => raw.set(p, y * (w * 4 + 1) + 1 + x * 4)); });
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 6; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
  return Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}
export const bits = hex => Array.from({ length: 8 }, (_, y) => { const byte = parseInt(hex.slice(y * 2, y * 2 + 2), 16); return Array.from({ length: 8 }, (_, x) => (byte >> (7 - x)) & 1); });
// Black pixels opaque, white pixels transparent, so a pattern can sit over any background; use .hc-pattern-*-opaque for white-backed tiles.
const tile = (hex, opaqueWhite) => png(bits(hex).map(row => row.map(b => b ? [0, 0, 0, 255] : opaqueWhite ? [255, 255, 255, 255] : [0, 0, 0, 0])));
const dataURI = buf => `url("data:image/png;base64,${buf.toString('base64')}")`;

const hc = read('patterns/hypercard-patterns.json'), sys = read('patterns/system-patterns.json');
fs.mkdirSync(path.join(root, 'patterns/png'), { recursive: true });
let css = `/* Generated by scripts/build-patterns.mjs from patterns/*.json. Do not edit by hand.
 * HyperCard's 40 palette patterns as 8x8 tiles: black pixels opaque, white pixels transparent.
 * Use: background-image: var(--hc-pattern-22); background-size: 8px 8px; image-rendering: pixelated;
 * Or the classes: <div class="hc-pattern hc-pattern-22"> (transparent) / hc-pattern-22-opaque (white backed). */
:root {
`;
for (const p of hc.patterns) {
  const transparent = tile(p.hex, false), opaque = tile(p.hex, true);
  fs.writeFileSync(path.join(root, `patterns/png/hc-${String(p.id).padStart(2, '0')}.png`), opaque);
  css += `  --hc-pattern-${p.id}: ${dataURI(transparent)}; /* ${p.name}${p.quickdraw ? `, QuickDraw ${p.quickdraw}` : ''} */\n`;
  css += `  --hc-pattern-${p.id}-opaque: ${dataURI(opaque)};\n`;
}
for (const [name, hex] of Object.entries(sys.quickdraw)) css += `  --qd-${name}: ${dataURI(tile(hex, false))};\n  --qd-${name}-opaque: ${dataURI(tile(hex, true))};\n`;
css += `}\n.hc-pattern { background-size: 8px 8px; background-repeat: repeat; image-rendering: pixelated; image-rendering: crisp-edges; }\n`;
for (const p of hc.patterns) css += `.hc-pattern-${p.id} { background-image: var(--hc-pattern-${p.id}); }\n.hc-pattern-${p.id}-opaque { background-image: var(--hc-pattern-${p.id}-opaque); }\n`;
for (const name of Object.keys(sys.quickdraw)) css += `.qd-${name} { background-image: var(--qd-${name}); }\n`;
fs.writeFileSync(path.join(root, 'css/patterns.css'), css);
sys.patterns.forEach((hex, i) => fs.writeFileSync(path.join(root, `patterns/png/sys-${String(i).padStart(2, '0')}.png`), tile(hex, true)));

// Browse hand cursor: 16x16 with 1x and 2x PNGs. hotspot (6,0).
const art = fs.readFileSync(path.join(root, 'cursors/browse-hand.txt'), 'utf8').split('\n').filter(l => /^[.#o]{16}$/.test(l));
const px = { '#': [0, 0, 0, 255], 'o': [255, 255, 255, 255], '.': [0, 0, 0, 0] };
const rows = art.map(l => [...l].map(c => px[c]));
fs.writeFileSync(path.join(root, 'cursors/browse-hand.png'), png(rows));
fs.writeFileSync(path.join(root, 'cursors/browse-hand@2x.png'), png(rows.flatMap(r => [r.flatMap(p => [p, p]), r.flatMap(p => [p, p])])));
const cursorCSS = `/* Generated by scripts/build-patterns.mjs. HyperCard's Browse tool hand, hotspot at the fingertip (6,0). */
:root {
  --hc-cursor-browse: url("data:image/png;base64,${png(rows).toString('base64')}") 6 0, pointer;
  --hc-cursor-browse-2x: -webkit-image-set(url("data:image/png;base64,${png(rows).toString('base64')}") 1x, url("data:image/png;base64,${png(rows.flatMap(r => [r.flatMap(p => [p, p]), r.flatMap(p => [p, p])])).toString('base64')}") 2x) 6 0, pointer;
}
.hc-cursor-browse, .hc-button, .hc-card a, .hc-card button { cursor: var(--hc-cursor-browse-2x); }
`;
fs.writeFileSync(path.join(root, 'css/cursors.css'), cursorCSS);
console.log(`patterns: ${hc.patterns.length} HyperCard + ${sys.patterns.length} System · css/patterns.css ${(css.length / 1024).toFixed(1)} KB · cursor written`);
