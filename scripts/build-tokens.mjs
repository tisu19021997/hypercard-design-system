// Flattens tokens/hypercard.tokens.json into CSS custom properties (css/tokens.css). Run: node scripts/build-tokens.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(fs.readFileSync(path.join(root, 'tokens/hypercard.tokens.json'), 'utf8'));
const lines = [];
const css = value => Array.isArray(value) ? value.map(v => /\s/.test(v) || /^[A-Z]/.test(v) && v.includes(' ') ? `"${v}"` : v.includes(' ') ? `"${v}"` : v).join(', ') : typeof value === 'object' ? null : String(value);
function walk(node, prefix) {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    const name = [...prefix, key];
    if (value && typeof value === 'object' && '$value' in value) {
      const v = css(value.$value);
      if (v !== null) lines.push(`  --hc-${name.join('-')}: ${v};${value.$description ? ` /* ${value.$description.replace(/\*\//g, '* /')} */` : ''}`);
      else for (const [k, x] of Object.entries(value.$value)) lines.push(`  --hc-${name.join('-')}-${k}: ${Array.isArray(x) ? x.join(' ') : typeof x === 'number' && !/count|columns|rows|strips|fps|ascent|descent|leading|advance|capHeight|xHeight|stem|space/.test(k) ? `${x}px` : x};`);
    } else if (value && typeof value === 'object') walk(value, name);
  }
}
walk(tokens, []);
const out = `/* Generated by scripts/build-tokens.mjs from tokens/hypercard.tokens.json. Do not edit by hand. */\n:root {\n${lines.join('\n')}\n}\n`;
fs.writeFileSync(path.join(root, 'css/tokens.css'), out);
console.log(`tokens: ${lines.length} custom properties → css/tokens.css`);
